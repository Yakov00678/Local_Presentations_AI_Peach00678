def parse_markdown_to_slides(text):
    # Разделяем текст по маркерам слайдов
    raw_slides = re.split(r'#\s*СЛАЙД\s*\d+', text)
    slides_data = []
    
    for raw in raw_slides:
        lines = [line.strip() for line in raw.split('\n') if line.strip()]
        if not lines:
            continue
            
        slide_info = {'title': '', 'content_lines': [], 'table': None}
        table_rows = []
        
        for line in lines:
            if line.startswith('---'):
                continue
            if line.startswith('##'):
                slide_info['title'] = line.replace('##', '').strip()
            elif line.startswith('|'):
                # Проверяем, не является ли строка разделителем типа |---|---|
                clean_line = line.replace('|', '').replace('-', '').replace(' ', '').strip()
                if not clean_line:
                    continue
                # Разбиваем строку на ячейки, убирая крайние пустые элементы
                cells = [c.strip() for c in line.split('|')][1:-1]
                if cells:
                    table_rows.append(cells)
            else:
                slide_info['content_lines'].append(line)
                
        if table_rows:
            slide_info['table'] = table_rows
            
        if slide_info['title'] or slide_info['content_lines'] or slide_info['table']:
            slides_data.append(slide_info)
        
    return slides_data

def get_unique_filename(folder, base_name, extension):
    filename = f"{base_name}{extension}"
    file_path = os.path.join(folder, filename)
    counter = 1
    while os.path.exists(file_path):
        filename = f"{base_name}_{counter}{extension}"
        file_path = os.path.join(folder, filename)
        counter += 1
    return file_path

def create_presentation(slides_data, selected_theme):
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    
    for data in slides_data:
        blank_layout = prs.slide_layouts[6]
        slide = prs.slides.add_slide(blank_layout)
        
        # Передаем управление дизайну слайда
        apply_slide_design(slide, data, theme_name=selected_theme)

    output_folder = "Presentations"
    if not os.path.exists(output_folder):
        os.makedirs(output_folder)
        
    base_name = f"presentation_theme_{selected_theme}"
    file_path = get_unique_filename(output_folder, base_name, ".pptx")
    
    prs.save(file_path)
    print(f"\n🚀 Готово! Презентация сохранена по пути: {file_path}")

